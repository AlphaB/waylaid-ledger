"""Validate the checked-in factual catalog and generate Data.lua, offline."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]

def build():
    catalog = json.loads((ROOT / 'data/catalog.json').read_text())
    materials = {int(i): name for i, name in catalog['materials'].items()}
    crates = catalog['crates']
    seen = set()
    lines = ['-- Generated by tools/build_catalog.py; edit data/catalog.json or refresh it.',
             f'-- Wowhead Forever item tooltips; retrieved {catalog["retrieved"]}.',
             'local _, addon = ...', 'addon.Crates = {']
    for crate in sorted(crates, key=lambda c: c['itemID']):
        assert isinstance(crate['itemID'], int) and crate['itemID'] not in seen
        seen.add(crate['itemID'])
        assert crate['name'].startswith('Waylaid Crate: ')
        assert crate['source'].startswith('https://www.wowhead.com/forever/item=')
        assert len(crate['sourceSHA256']) == 64
        assert 2 <= len(crate['options']) <= 5
        lines += [f'    [{crate["itemID"]}] = {{', f'        name = {json.dumps(crate["name"])},', '        options = {']
        for option in crate['options']:
            assert option['itemID'] in materials
            assert isinstance(option['quantity'], int) and 0 < option['quantity'] <= 1000
            lines += [f'            {{ itemID = {option["itemID"]}, quantity = {option["quantity"]} }},']
        lines += ['        },', '    },']
    lines += ['}', '', 'addon.MaterialNames = {']
    lines += [f'    [{i}] = {json.dumps(n)},' for i, n in sorted(materials.items())]
    lines += ['}', '']
    (ROOT / 'WaylaidLedger/Data.lua').write_text('\n'.join(lines))
    print(f'{len(crates)} crates, {sum(len(c["options"]) for c in crates)} options, {len(materials)} unique materials')

if __name__ == '__main__':
    build()
