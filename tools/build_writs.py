"""Validate the checked-in writ facts and generate Lua offline."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]

def build():
    catalog = json.loads((ROOT / 'data/writs.json').read_text())
    lines = ['-- Generated by tools/build_writs.py from Wowhead Forever quest objectives.',
             f'-- Retrieved {catalog["retrieved"]}; see data/writs.json for provenance.',
             'local _, addon = ...', 'addon.Writs = {']
    materials, seen = {}, set()
    for writ in catalog['writs']:
        assert writ['itemID'] not in seen and writ['requirements']
        seen.add(writ['itemID'])
        assert writ['name'].startswith("Craftsman's Writ:")
        assert writ['source'].startswith('https://www.wowhead.com/forever/quest=')
        lines += [f'    [{writ["itemID"]}] = {{ name = {json.dumps(writ["name"])}, questID = {writ["questID"]}, requirements = {{']
        for required in writ['requirements']:
            assert required['itemID'] != writ['itemID'] and isinstance(required['quantity'], int) and required['quantity'] > 0
            materials[required['itemID']] = required['name']
            lines += [f'        {{ itemID = {required["itemID"]}, quantity = {required["quantity"]} }},']
        lines += ['    } },']
    lines += ['}', 'addon.WritMaterialNames = {']
    lines += [f'    [{i}] = {json.dumps(n)},' for i, n in sorted(materials.items())]
    lines += ['}', '']
    (ROOT / 'WaylaidLedger/WritData.lua').write_text('\n'.join(lines))
    print(f'Generated {len(seen)} writs and {len(materials)} delivery item names')

if __name__ == '__main__':
    build()
